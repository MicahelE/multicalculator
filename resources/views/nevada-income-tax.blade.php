<h2>Does Nevada Have a State Income Tax?</h2>

<p>No. Nevada is one of nine states with no state income tax on wages, and its constitution bans a personal income tax. Your paycheck only loses federal income tax, Social Security and Medicare, plus anything you choose to put into a 401(k) or benefits. This calculator shows what that leaves you, and how much more you keep than on the same salary in neighboring California.</p>

<h3>What comes out of a Nevada paycheck</h3>
<div class="card bg-light p-3 mb-4">
    <p class="mb-1"><strong>Federal income tax:</strong> 2026 brackets after the standard deduction ($16,100 single, $32,200 joint)</p>
    <p class="mb-1"><strong>Social Security:</strong> 6.2% up to $184,500 of wages</p>
    <p class="mb-1"><strong>Medicare:</strong> 1.45%, plus 0.9% over $200,000 ($250,000 joint)</p>
    <p class="mb-0"><strong>Nevada income tax:</strong> $0</p>
</div>

<h3>Example</h3>
<p>A single filer in Las Vegas earns $85,000 and puts 5% into a 401(k). Federal income tax is $8,935 and Social Security plus Medicare is $6,502.50. Take-home pay is <strong>$65,312.50</strong> a year, about $5,443 a month. The same job in California would leave $61,082.38 after $3,125 of state income tax and $1,105 of SDI, so living in Nevada keeps about <strong>$4,230</strong> more a year.</p>

<h3>How Nevada makes up the difference</h3>
<p>No income tax doesn't mean no taxes. Nevada leans on sales tax (a 6.85% state rate, and about 8.4% in Clark County), gaming and hotel taxes paid largely by tourists, and a Modified Business Tax that employers pay on payroll. Property taxes are moderate, and annual increases on a primary home are capped.</p>

<div class="calculator-faq mt-4">
    <h3>Frequently Asked Questions</h3>

    <h4>Does Nevada tax retirement income or Social Security?</h4>
    <p>No. With no income tax, Nevada doesn't tax pensions, 401(k) or IRA withdrawals, or Social Security. Federal tax still applies.</p>

    <h4>If I work remotely for a California company, do I owe California tax?</h4>
    <p>Generally not on work you physically do in Nevada, as long as you're a Nevada resident. Days you work in California can be taxed by California, so keep records.</p>

    <h4>Does no tax on tips matter more in Nevada?</h4>
    <p>Yes, for many hospitality workers. Tips are already free of state tax in Nevada, and the federal <a href="/no-tax-on-tips">no tax on tips deduction</a> can cut the federal tax on them too.</p>
